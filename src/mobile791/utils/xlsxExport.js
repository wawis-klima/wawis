function serializeContractorAddresses(contractor = {}) {
  const addresses = Array.isArray(contractor?.addresses) ? contractor.addresses : [];
  if (!addresses.length) return '';
  return JSON.stringify(addresses.map((address) => ({
    id: String(address?.id || ''),
    label: String(address?.label || ''),
    city: String(address?.city || ''),
    street: String(address?.street || ''),
    notes: String(address?.notes || ''),
    is_primary: address?.is_primary === true,
  })));
}

export function exportContractorsToXlsx(contractors = []) {
  const headers = ['Nazwa kontrahenta', 'Osoba kontaktowa', 'Telefon', 'Email', 'Miasto', 'Ulica', 'Adresy (JSON)', 'NIP', 'Notatki', 'Status'];
  const rows = contractors.map((contractor) => [
    contractor?.company_name || '',
    contractor?.contact_person || '',
    contractor?.phone || '',
    contractor?.email || '',
    contractor?.city || '',
    contractor?.street || '',
    serializeContractorAddresses(contractor),
    contractor?.nip || '',
    contractor?.notes || '',
    contractor?.is_active ? 'Aktywny' : 'Nieaktywny',
  ]);
  const files = buildWorkbookFiles({ headers, rows });
  const zipBytes = createStoredZip(files);
  const blob = new Blob([zipBytes], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
  const safeDate = new Date().toISOString().slice(0, 10);
  return {
    blob,
    fileName: `kontrahenci-${safeDate}.xlsx`,
  };
}

export function triggerBlobDownload(blob, fileName) {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = fileName;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}
