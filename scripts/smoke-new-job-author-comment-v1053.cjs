const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8');

(async () => {
  const { getNewJobCommentConfig } = await import(pathToFileURL(path.join(root, 'src/mobile791/modules/new-job-comment.js')).href);
  const modal = read('src','mobile791','components','modals','JobFormModal.jsx');
  const actions = read('src','mobile791','hooks','useSelectedJobActions.js');
  const jobsForm = read('src','mobile791','modules','jobs-form.js');
  const micCss = read('src','mobile791','components','modals','new-job-comment-mic-v1311.css');
  const admin = getNewJobCommentConfig(true), worker = getNewJobCommentConfig(false);
  assert.deepEqual(admin, { field: 'admin_note', label: 'Komentarz administratora', placeholder: 'Komentarz administratora', voiceLabel: 'Komentarz administratora' });
  assert.deepEqual(worker, { field: 'worker_comment', label: 'Komentarz', placeholder: 'Komentarz do montażu', voiceLabel: 'Komentarz do montażu' });
  assert.match(modal, /getNewJobCommentConfig\(isAdmin\)/);
  assert.ok(modal.includes('{!editingJobId ? (') && modal.includes('workerNewClientCommentBlock'), 'Nowe zlecenie zachowuje formularz komentarza');
  assert.ok(modal.includes('{newJobCommentConfig.label}'), 'Etykieta komentarza zależy od roli');
  assert.ok(modal.includes('label={newJobCommentConfig.voiceLabel}'), 'Głos ma przypisaną rolę');
  assert.ok(modal.includes('[newJobCommentConfig.field]: appendVoiceNoteText(prev[newJobCommentConfig.field], value)'), 'Dyktowanie zapisuje właściwe pole');
  assert.ok(modal.includes("value={jobForm[newJobCommentConfig.field] || ''}"), 'Pole tekstowe czyta właściwą wartość');
  assert.ok(modal.includes('updateField(newJobCommentConfig.field, e.target.value)'), 'Ręczny wpis zapisuje właściwe pole');
  assert.ok(modal.includes('updateField(newJobCommentConfig.field, "")'), 'Czyszczenie dotyczy wyłącznie bieżącej roli');
  assert.ok(modal.includes('{isAdmin && editingJobId ? (') && modal.includes('jobFormAdminFields'), 'Edycja komentarza admina pozostaje');
  assert.match(micCss, /workerNewClientCommentMicActions \.voiceFieldMicBtn/, 'Zachowujemy kompaktowy mikrofon');
  assert.ok(actions.includes("if (!isAdmin && String(form.worker_comment || '').trim() && createdJob?.id)"), 'Tylko pracownik dodaje zwykły komentarz podczas utworzenia');
  assert.ok(actions.includes("type: 'Komentarz'"));
  assert.match(jobsForm, /admin_note: isAdmin \? \(resolvedForm\.admin_note\.trim\(\) \|\| null\) : null/, 'Admin note musi trafić do INSERT jobs');
  assert.ok(jobsForm.includes("admin_note: ''"), 'Pracownik nie może ustawić notatki administracyjnej');
  console.log('PASS smoke-new-job-author-comment-v1053 + role-routing-v1321');
})().catch((error) => { console.error(error); process.exitCode = 1; });
